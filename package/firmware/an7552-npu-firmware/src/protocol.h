#ifndef AN7552_PROTOCOL_H
#define AN7552_PROTOCOL_H

#define AN7552_MAGIC 0x7552d001U
#define AN7552_HOST_BASE 0x1e903000U
#define AN7552_NPU_BASE 0x3e903000U
#define AN7552_STRIDE 64U
#define AN7552_CORES 2U

/* Host-reserved shared memory and packet buffers. */
#define AN7552_TDMA_CONTROL 0x180U
#define AN7552_STATION_HOST 0x842a0000U
#define AN7552_STATION_NPU 0x442a0000U
#define AN7552_STATION_COUNT 2048U
#define AN7552_STATION_AUTHORIZED 1U
#define AN7552_STATION_MLO 2U
#define AN7552_STATION_CONTROL 0x380U
#define AN7552_QOS_HOST 0x84290000U
#define AN7552_QOS_NPU 0x44290000U
#define AN7552_QOS_COUNT 256U
#define AN7552_QOS_STRIDE 128U
/* ABI 4: shared MLD counters and second-radio aggregate continuation. */
#define AN7552_PN_DOMAIN_HOST 0x84300000U
#define AN7552_PN_DOMAIN_NPU 0x44300000U
#define AN7552_PN_RADIO_STATE_HOST 0x84380000U
#define AN7552_PN_RADIO_STATE_NPU 0x44380000U
#define AN7552_PN_DOMAIN_INDEX_BITS 11U
#define AN7552_PN_ENTRY_SIZE 256U
#define AN7552_TXFREE_RING_HOST 0x842b0000U
#define AN7552_TXFREE_BUFFER_HOST 0x84c00000U
#define AN7552_TXFREE_COUNT 512U
#define AN7552_RX_DATA_RING_HOST 0x842c0000U
#define AN7552_RX_COMPLETE_HOST 0x842d0000U
#define AN7552_RX_EMI_HOST 0x842d8000U
#define AN7552_RX_FREE_HOST 0x842e0000U
#define AN7552_RX_STATE_HOST 0x842e6000U
#define AN7552_PPE_DOMAIN_HOST 0x841e0000U
#define AN7552_PPE_DOMAIN_STRIDE 32U
#define AN7552_PPE_MODE_BRIDGE 4U
#define AN7552_RX_BUFFER_HOST 0x84e00000U
#define AN7552_RX_BUFFER_COUNT 6144U
#define AN7552_RX_RING_COUNT 1536U
#define AN7552_RX_TOKEN_BASE 32768U
#define AN7552_RX_DATA_CONTROL 0x600U
#define AN7552_RRO_CONTROL 0x500U
#define AN7552_TXFREE_CONTROL 0x400U
#define AN7552_FORWARD_CONTROL 0x300U
#define AN7552_FORWARD_WORK_HOST 0x84280000U
#define AN7552_FORWARD_WORK_NPU 0x44280000U
#define AN7552_NATIVE_CONTROL 0x200U
#define AN7552_NATIVE_RING_HOST 0x84240000U
#define AN7552_NATIVE_RING_COUNT 2048U
#define AN7552_TXWI_HOST 0x84a00000U
#define AN7552_TXWI_NPU 0x44a00000U
#define AN7552_TXWI_TOKENS 16384U
#define AN7552_PARK_CONTROL 0x1e0U
#define AN7552_PARK_ACK 0x1e4U
#define AN7552_PARK_MAGIC 0x7552a11dU
#define AN7552_TDMA_RING_HOST 0x84400000U
#define AN7552_TDMA_RING_NPU 0x44400000U
#define AN7552_TDMA_BUFFER_HOST 0x84410000U
#define AN7552_TDMA_BUFFER_NPU 0x44410000U
#define AN7552_TDMA_COUNT 1024U
#define AN7552_TDMA_BANDS 2U
#define AN7552_DIRECT_TOKENS (AN7552_TDMA_COUNT * AN7552_TDMA_BANDS)
#define AN7552_TDMA_BUFFER_SIZE 2048U

#if AN7552_PPE_DOMAIN_HOST + AN7552_RX_BUFFER_COUNT * AN7552_PPE_DOMAIN_STRIDE > AN7552_NATIVE_RING_HOST
#error "Bridge domain state overlaps native rings"
#endif

#if AN7552_QOS_HOST < AN7552_FORWARD_WORK_HOST + AN7552_DIRECT_TOKENS * 16
#error "QoS policy overlaps forwarding work"
#endif
#if AN7552_PPE_DOMAIN_HOST + AN7552_RX_BUFFER_COUNT * AN7552_PPE_DOMAIN_STRIDE > AN7552_NATIVE_RING_HOST
#error "Bridge domain state overlaps native rings"
#endif

#if AN7552_QOS_HOST + AN7552_QOS_COUNT * AN7552_QOS_STRIDE > AN7552_STATION_HOST
#error "QoS policy overlaps station state"
#endif

#if (1U << AN7552_PN_DOMAIN_INDEX_BITS) != AN7552_STATION_COUNT
#error "Replay domain handle index does not cover the station table"
#endif
#if AN7552_PN_DOMAIN_HOST + AN7552_STATION_COUNT * AN7552_PN_ENTRY_SIZE > AN7552_PN_RADIO_STATE_HOST
#error "Replay domains overlap radio continuation state"
#endif
#if AN7552_PN_RADIO_STATE_HOST + AN7552_STATION_COUNT * AN7552_PN_ENTRY_SIZE > AN7552_TDMA_RING_HOST
#error "Radio continuation state overlaps TDMA memory"
#endif

#endif
